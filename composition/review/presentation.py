"""Read-only operator presentation; never grants production approval or scans files."""

from dataclasses import dataclass
from pathlib import Path


def next_step(status, *, accepted=False, stale=False):
    if stale:
        return "Source or settings changed. Check again before accepting data or reviewing production."
    key=str(status).casefold()
    if key in ("running","checking"):
        return "Background work is running. Inspect progress or cancel at a safe checkpoint."
    if key in ("blocked","failed"):
        return "Open Issues, return to the indicated settings and check again."
    if key in ("cancelled","interrupted"):
        return "Completed results are retained. Check unfinished work again before retrying."
    if key.startswith("completed"):
        return "Open validated outputs and reports; completed work is not automatically rerun."
    if key=="checked":
        return "Review the plan and warnings, then Confirm production."
    if accepted:
        return "Data accepted. Open Production Review to check the output plan and confirm generation."
    if key in ("needs review","ready","no records"):
        return "Inspect records, mappings and exclusions. Accept data & jobs, then open Production Review."
    return "Check inputs and settings, then Check & Preview. No production files are generated by a step check."


@dataclass(frozen=True)
class DashboardMetric:
    key: str
    label: str
    value: str


@dataclass(frozen=True)
class BarcodeDisplay:
    state: str
    detail: str
    expected: int | None = None
    verified: int | None = None
    unverified: int | None = None


@dataclass(frozen=True)
class FontDisplay:
    state: str
    detail: str
    count: int | None = None
    records: int | None = None
    pages: int | None = None
    report: str = ""
    reference_label: str = "record(s)"


def _count(value):
    return value if type(value) is int and value >= 0 else None


def _number(value, missing="Not Available"):
    count = _count(value)
    return f"{count:,}" if count is not None else missing


def _text(value):
    return str(value) if value is not None and str(value).strip() else "Not Available"


def dashboard_inputs(state):
    """Presentation only, after confirmation. Never used to grant authorization.

    Workflow execution updates status/result fields in the existing UI model.
    Keep every input/unknown field, removing only known execution bookkeeping
    at run/job boundaries; never walk customer records or template contents.
    """
    runtime = {
        "status",
        "started_at",
        "finished_at",
        "report_dir",
        "error",
        "stage",
        "result",
        "history",
        "approved",
        "state_save_error",
        "report_error",
        "published_records",
        "unpublished_records",
        "warnings",
        "notification_errors",
    }

    def run_view(value):
        if not isinstance(value, dict) or "jobs" not in value:
            return value
        view = {key: item for key, item in value.items() if key not in runtime}
        view["jobs"] = []
        for job in value["jobs"]:
            item = {key: val for key, val in job.items() if key not in runtime}
            if isinstance(item.get("batch"), dict):
                item["batch"] = run_view(item["batch"])
            view["jobs"].append(item)
        return view

    return {key: run_view(value) if key in {"batch", "run"} else value for key, value in state.items()}


def _reports_published(review, result):
    summary = review.get("summary", {})
    return (
        summary.get("backend") == "reports"
        and summary.get("records") == 0
        and summary.get("pages") == 0
        and result.get("status") == "completed"
        and result.get("generated_pages") == 0
        and result.get("generated_files") == 0
        and not result.get("output_pdf")
        and bool(result.get("report_dir"))
    )


def _generation_for(review, generation):
    """UI result binding is not authorization; never borrow another job's result."""
    if not review or not generation:
        return None
    identity = {
        "snapshot_id": review.get("snapshot_id"),
        "fingerprint": review.get("fingerprint"),
        "job_id": review.get("summary", {}).get("job_id"),
    }
    if any(not value or generation.get(key) != value for key, value in identity.items()):
        return None
    result = generation.get("result")
    if result:
        if result.get("job_id") != identity["job_id"]:
            return None
        planned, expected = review.get("summary", {}).get("pages"), result.get("expected_pages")
        if _count(planned) is not None and _count(expected) is not None and planned != expected:
            return None
    return generation


def _audit_scope_known(context):
    # Metadata only: no payload evaluation or repeat of production validation.
    # Template final audit only admits inserter/fixed-layout profiles. Overlay
    # audits its visible barcode marks. Unknown configurations stay unproven.
    if context.get("kind") == "overlay":
        return True
    template = context.get("job", {}).get("template")
    if context.get("kind") != "template" or not isinstance(template, dict):
        return False
    pages = template.get("pages", [{"elements": template.get("elements", [])}])
    for page in pages:
        for element in page.get("elements", []):
            if element.get("type") in {"qr", "code128", "i25"}:
                profile = element.get("barcode_profile") or {}
                if profile.get("preset") != "inserter_i25_18" and profile.get("layout_mode") != "fixed":
                    return False
    return True


def _planned_barcodes(review, current):
    if not review:
        return BarcodeDisplay("Not Checked", "No checked barcode plan.")
    summary = review.get("summary", {})
    expected = _count(summary.get("expected_barcodes"))
    if not current:
        return BarcodeDisplay("Not Checked", "Review is outdated; check again.")
    if any(i.get("severity") == "error" and i.get("action") == "barcode" for i in review.get("issues", [])):
        return BarcodeDisplay("Failed", "Open Issues to inspect the barcode plan.", expected)
    complete = (
        review.get("complete") is True
        and review.get("status") == "checked"
        and summary.get("barcode_check_complete") is True
    )
    if complete and expected is not None:
        if expected == 0:
            return BarcodeDisplay("Not Applicable", "Complete plan contains no visible barcodes.", 0)
        return BarcodeDisplay(
            "Passed", "Planned payloads and placement checked; this is not final PDF decoding.", expected
        )
    return BarcodeDisplay(
        "Incomplete" if expected is not None else "Not Checked",
        "Barcode plan is not fully checked.",
        expected,
    )


def _final_barcodes(review, generation, current):
    if not current or not generation or generation.get("phase") != "finished":
        return BarcodeDisplay(
            "Not Checked", "Final decoding evidence is not available for this checked snapshot."
        )
    result = generation.get("result") or {}
    if _reports_published(review, result) and _planned_barcodes(review, current).state == "Not Applicable":
        return BarcodeDisplay("Not Applicable", "Reports-only job; no PDF or barcode decoding was required.")
    expected, rendered, decoded = (
        _count(result.get(key)) for key in ("expected_barcodes", "rendered_barcodes", "decoded_barcodes")
    )
    if any(value is None for value in (expected, rendered, decoded)):
        return BarcodeDisplay("Not Checked", "Final decoding counters are unavailable.")
    if decoded > expected or rendered != expected:
        return BarcodeDisplay(
            "Incomplete",
            "Final audit counters are inconsistent; inspect the existing production report.",
            expected,
            decoded,
        )
    missing = expected - decoded
    published = (
        result.get("status") == "completed"
        and _count(result.get("generated_files", result.get("published_files"))) not in (None, 0)
        and bool(result.get("output_pdf"))
    )
    planned = _planned_barcodes(review, current)
    if expected == 0:
        if (published or _reports_published(review, result)) and planned.state == "Not Applicable":
            return BarcodeDisplay(
                "Not Applicable", "Complete plan has no visible barcodes; no decode required.", 0, 0, 0
            )
        return BarcodeDisplay(
            "Incomplete",
            "Zero audit targets do not establish coverage of configured barcodes.",
            expected,
            decoded,
            missing,
        )
    if missing:
        state = "Failed" if result.get("status") == "failed" and decoded > 0 else "Incomplete"
        return BarcodeDisplay(
            state,
            "Coverage is for final audit targets only; inspect production results.",
            expected,
            decoded,
            missing,
        )
    if not published:
        return BarcodeDisplay(
            "Incomplete",
            "Decode counters are available, but validated output was not published.",
            expected,
            decoded,
            missing,
        )
    if not _audit_scope_known(review.get("context", {})):
        return BarcodeDisplay(
            "Incomplete",
            "Audit targets decoded; Direct Content or other object types are not established as covered. No all-barcode coverage is claimed.",
            expected,
            decoded,
            missing,
        )
    return BarcodeDisplay(
        "Passed",
        "Final audit targets decoded exactly. Machine acceptance remains separate.",
        expected,
        decoded,
        missing,
    )


def _fonts(review, generation):
    summary = review.get("summary", {}) if review else {}
    result = generation.get("result") if generation and generation.get("phase") == "finished" else None
    if result:
        scan = result.get("font_scan", {})
        count = _count(result.get("repaired_glyphs", scan.get("occurrences")))
        records = _count(result.get("repaired_records", scan.get("records")))
        complete = scan.get("complete") is True
        report, stage = result.get("glyph_repair_report", ""), "Production font scan (publication separate)"
        if (
            not report
            and review.get("context", {}).get("kind") == "overlay"
            and result.get("report_dir")
            and count is not None
        ):
            report = str(Path(result["report_dir"]) / "glyph-repairs.csv")
    else:
        scan = summary.get("font_scan", {})
        count = _count(summary.get("font_substitutions", scan.get("occurrences")))
        records = _count(scan.get("records"))
        complete = scan.get("complete") is True or (
            review
            and review.get("complete") is True
            and review.get("status") == "checked"
            and "font_substitutions" in summary
        )
        report, stage = summary.get("font_report", ""), "Preflight font scan"
    state = (
        "Not Available"
        if count is None
        else "Incomplete"
        if not complete
        else "Review Required"
        if count
        else "Passed"
    )
    detail = (
        stage
        + ": character occurrences, not a layout-safety guarantee. Physical output page mapping is not provided; use record/template references in the report."
    )
    unit = "output-page scan entries" if review and review.get("context", {}).get("kind") == "overlay" else "record(s)"
    return FontDisplay(state, detail, count, records, report=str(report or ""), reference_label=unit)


@dataclass(frozen=True)
class ReviewDashboardModel:
    status: str
    status_label: str
    job_id: str
    snapshot_id: str
    fingerprint: str
    metrics: tuple[DashboardMetric, ...]
    planned_barcode: BarcodeDisplay
    final_barcode: BarcodeDisplay
    fonts: FontDisplay
    errors: int | None
    warnings: int | None

    @classmethod
    def from_review(
        cls,
        review,
        *,
        current=True,
        checking=False,
        confirming=False,
        confirmed=False,
        confirmation_available=False,
        acknowledged=False,
        cancelled=False,
        check_failed=False,
        generation=None,
    ):
        summary = review.get("summary", {}) if review else {}
        issues = review.get("issues", []) if review else []
        errors = sum(i.get("severity") == "error" for i in issues) if review and isinstance(review.get("issues"), list) else None
        warnings = sum(i.get("severity") == "warning" for i in issues) if review and isinstance(review.get("issues"), list) else None
        bound = _generation_for(review, generation) if confirmed else None
        result = bound.get("result") or {} if bound and bound.get("phase") == "finished" else {}
        if not current and review:
            status, label = "stale", "Review outdated - check again"
        elif cancelled:
            status, label = "cancelled", "Review cancelled - confirmation unavailable"
        elif checking:
            status, label = "checking", "Checking production inputs"
        elif confirming:
            status, label = "confirming", "Confirming production - not yet authorized"
        elif bound and bound.get("phase") == "running":
            status, label = "generating", "Generating output - publication not yet confirmed"
        elif bound and (bound.get("phase") == "failed" or result.get("status") == "failed"):
            status, label = "failed", "Generation failed - inspect production results"
        elif bound and (bound.get("phase") == "cancelled" or result.get("status") == "cancelled"):
            status, label = "cancelled", "Generation cancelled - inspect retained results"
        elif (
            result.get("status") == "completed"
            and _count(result.get("generated_files", result.get("published_files"))) not in (None, 0)
            and result.get("output_pdf")
        ):
            status, label = "generated", "Output generated and published"
        elif result and _reports_published(review, result):
            status, label = "reports_published", "Reports published - no PDF was required"
        elif bound and bound.get("phase") == "finished" and not result:
            status, label = "outcome_unavailable", "Generation ended - matching final result not available"
        elif confirmed:
            status, label = "confirmed", "Production confirmed - not proof of published output"
        elif check_failed or (review and (review.get("status") == "blocked" or errors)):
            status, label = "blocked", "Production blocked - open Issues"
        elif review and review.get("status") == "cancelled":
            status, label = "cancelled", "Review cancelled - check again"
        elif warnings and not acknowledged:
            status, label = "warnings", "Warnings require acknowledgement"
        elif confirmation_available:
            status, label = "ready_to_confirm", "Ready to confirm production - not yet authorized"
        elif review and review.get("complete") is True and review.get("status") == "checked":
            status, label = "ready_for_review", "Check complete - review before confirming"
        else:
            status, label = "not_checked", "Production not checked"
        stocks = summary.get("stock_sheets")
        stock_text = (
            " / ".join(f"{k}: {_number(v)} sheets" for k, v in stocks.items())
            if stocks
            else "No stock assignment"
            if stocks == {}
            else "Not Available"
        )
        metrics = (
            DashboardMetric("mailpieces", "Mailpieces / envelopes", _number(summary.get("records"))),
            DashboardMetric("planned_pages", "Planned output pages", _number(summary.get("pages"))),
            DashboardMetric("sheets", "Physical sheets", _number(summary.get("sheets"))),
            DashboardMetric("blank_backs", "Inserted blank backs", _number(summary.get("inserted_blanks"))),
            DashboardMetric("printing", "Printing mode", _text(summary.get("printing"))),
            DashboardMetric(
                "actual_pages",
                "Actual generated pages",
                _number(result.get("generated_pages")) if result else "Not generated",
            ),
            DashboardMetric("stocks", "Paper stocks", stock_text),
            DashboardMetric("printer_profile", "Printer profile", _text(summary.get("printer_profile"))),
            DashboardMetric("settings_source", "Print settings source", _text(summary.get("media_source"))),
            DashboardMetric("output_destination", "Selected output folder", _text(summary.get("output_dir"))),
            DashboardMetric("output_name", "Planned PDF name", _text(summary.get("output_name"))),
            DashboardMetric(
                "published_output",
                "Published PDF",
                _text(result.get("output_pdf"))
                if status == "generated"
                else "No PDF required"
                if status == "reports_published"
                else "Not published",
            ),
            DashboardMetric(
                "published_reports",
                "Published reports",
                _text(result.get("report_dir"))
                if status in {"generated", "reports_published"}
                else "Not published",
            ),
        )
        return cls(
            status,
            label,
            str(summary.get("job_id") or ""),
            str(review.get("snapshot_id") or "") if review else "",
            str(review.get("fingerprint") or "") if review else "",
            metrics,
            _planned_barcodes(review, current),
            _final_barcodes(review, bound, current),
            _fonts(review, bound),
            errors,
            warnings,
        )
